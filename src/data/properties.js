export const getFeaturedProperties = () => properties.filter(p => p.featured);
export const getPropertyById = (id) => properties.find(p => p.id === id);
export const getRelatedProperties = (currentId, limit = 3) => {
  const current = properties.find(p => p.id === currentId);
  if (!current) return properties.slice(0, limit);
  return properties
    .filter(p => p.id !== currentId && (p.purpose === current.purpose || p.type === current.type))
    .slice(0, limit);
};
